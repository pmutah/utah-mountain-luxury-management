import assert from 'node:assert/strict';
import test from 'node:test';
import { cleanEventLine, cleanHouseCards, cleanJobsEmptyLine, cleanTurnsLine, cleanTurnsVisible } from './clean-ready.ts';

test('the cleaner still has each house when the turnover list cannot be read', () => {
  const cards = cleanHouseCards('en');
  assert.deepEqual(
    cards.map((card) => card.house),
    ['river', 'ranch', 'lindon'],
  );
  const river = cards[0];
  const ranch = cards[1];
  const text = JSON.stringify(cards);
  assert.match(river.rules.join(' '), /mountain neighborhood/);
  assert.match(ranch.rules.join(' '), /10 PM to 8 AM/);
  assert.match(river.when, /Checkout at 11:00 AM/);
  assert.match(river.unread, /does not name a stay/);
  assert.match(river.essentials.join(' '), /Winter driving/);
  assert.match(ranch.essentials.join(' '), /close on Sundays/i);
  assert.equal(river.essentials.some((line) => /door\s*code|wi-?fi|password|\$/i.test(line)), false);
  assert.match(river.prep, /grocery drop/);
  assert.match(river.prep, /does not say that anyone asked/);
  assert.match(river.clock, /5 hours, from 11:00 AM to 4:00 PM/);
  assert.match(river.clock, /makes it 2 hours/);
  assert.match(river.clock, /does not say that anyone asked/);
  assert.match(ranch.prep, /hot tub/);
  assert.match(cards[2].prep, /no hot tub and no grocery drop/);
  assert.equal(cards[2].prep.toLowerCase().includes('asked for'), false);
  assert.ok(river.steps.some((step) => step.id === 'photos' && step.label === 'Photo each room before you leave'));
  assert.ok(river.steps.some((step) => step.label === 'Strip and remake every bed'));
  assert.ok(river.leaving.some((line) => line.includes('dishwasher')));
  assert.ok(river.leaving.some((line) => line.includes('Only toilet paper')));
  assert.ok(ranch.leaving.some((line) => line.includes('hot tub cover')));
  assert.equal(cards[2].leaving.some((line) => /toilet paper|hot tub/i.test(line)), false);
  assert.equal(text.includes('$'), false);
  assert.equal(/password|code\s*\d/i.test(text), false);
  assert.equal(text.toLowerCase().includes('guest name'), false);
  assert.match(river.photoGuide ?? '', /eight king suites/);
  assert.match(river.photoGuide ?? '', /not a new list/);
  assert.match(river.photoGuide ?? '', /not uploaded/);
  assert.equal(ranch.photoGuide, null);
  assert.equal(cards[2].photoGuide, null);
  assert.equal((river.photoGuide ?? '').includes('$'), false);
  const event = cleanEventLine('river', '2026-10-30');
  assert.match(event, /BYU at Utah/);
  assert.match(event, /2 nights/);
  assert.match(event, /does not name a stay/);
  assert.match(event, /Nothing was booked or sent/);
  assert.equal(event.includes('Arizona State'), false);
  assert.equal(event.includes('$'), false);
  assert.equal(event.replace(/does not say the house is open/g, '').toLowerCase().includes('house is open'), false);
  const spanish = cleanEventLine('river', '2026-10-30', 'es');
  assert.match(spanish, /no nombra una estancia/);
  assert.equal(spanish.includes('$'), false);
});

test('the Spanish card keeps the mountain quiet hours', () => {
  const cards = cleanHouseCards('es');
  const river = cards[0];
  const ranch = cards[1];
  const text = JSON.stringify(cards);
  assert.match(river.rules.join(' '), /vecindario de montaña/);
  assert.match(river.when, /Salida a las 11:00 AM/);
  assert.match(river.unread, /no nombra una estancia/);
  assert.match(river.prep, /entrega de víveres/);
  assert.match(river.prep, /no dice que alguien lo pidió/);
  assert.match(river.clock, /5 horas, de 11:00 AM a 4:00 PM/);
  assert.match(river.clock, /no dice que alguien lo pidió/);
  assert.ok(river.steps.some((step) => step.id === 'photos' && step.label === 'Foto de cada cuarto antes de irte'));
  assert.ok(river.steps.some((step) => step.label === 'Quita y tiende cada cama'));
  assert.match(river.essentials.join(' '), /Conducción en invierno/);
  assert.equal(river.essentials.join(' ').includes('Winter driving'), false);
  assert.match(ranch.essentials.join(' '), /cierran los domingos/);
  assert.match(river.notes.join(' '), /Séptico/);
  assert.match(ranch.notes.join(' '), /Jacuzzi/);
  assert.equal(ranch.notes.join(' ').includes('Hot tub'), false);
  assert.equal(text.includes('$'), false);
  assert.equal(/password|code\s*\d/i.test(text), false);
  const line = cleanTurnsLine([{ house: 'ranch', checkOut: '2026-11-08' }], 'en');
  assert.match(line, /Next checkouts: The Ranch House Nov 8/);
  assert.match(line, /does not name a stay/);
  assert.equal(line.includes('$'), false);
  assert.equal(line.includes('Turn Guest'), false);
  const none = cleanTurnsLine([], 'en');
  assert.match(none, /No checkouts in the next two weeks/);
  assert.equal(cleanTurnsVisible([], 1), false);
  assert.equal(cleanTurnsVisible([], 0), true);
  assert.equal(cleanTurnsVisible([{ checkOut: '2026-11-08' }], 1), true);
  assert.equal(cleanTurnsVisible(null, 1), false);
  assert.equal(cleanJobsEmptyLine(1, null), null);
  assert.equal(cleanJobsEmptyLine(0, [{ checkOut: '2026-11-08' }]), null);
  assert.equal(cleanJobsEmptyLine(0, []), null);
  const unread = cleanJobsEmptyLine(0, null, 'en');
  assert.match(unread ?? '', /could not be read/);
  assert.match(unread ?? '', /Nothing was booked or sent/);
  assert.equal((unread ?? '').includes('No checkouts'), false);
  const unreadEs = cleanJobsEmptyLine(0, null, 'es');
  assert.match(unreadEs ?? '', /no se pudieron leer/);
  assert.equal((unreadEs ?? '').includes('$'), false);
});
